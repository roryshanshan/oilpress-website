export const classifyPage = (path = '') => {
  if (/\/contact\/?$/.test(path)) return 'contact'
  if (/\/products(?:\/|$)/.test(path)) return 'product'
  if (/\/solutions(?:\/|$)/.test(path)) return 'solution'
  if (/\/(?:about|advantages)(?:\/|$)/.test(path)) return 'company'
  return 'guide'
}

