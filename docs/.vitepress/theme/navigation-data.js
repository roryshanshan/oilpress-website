export const getLocaleCopy = (locale) => copy[locale] || copy.en

export const getLocaleFromPath = (value = '') => {
  const match = String(value).match(/^\/?(en|zh|ru|fr|vi|bn)(?:\/|$)/)
  return match ? match[1] : 'en'
}

export const localizedPath = (locale, path = '/') => {
  if (path === '/') return `/${locale}`
  const clean = `/${String(path).replace(/^\/+|\/+$/g, '')}`
  return `/${locale}${clean}`
}

